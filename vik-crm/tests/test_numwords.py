import pytest

from app.numwords import normalize


@pytest.mark.parametrize("said,expected", [
    ("Плюс пять процентов работам", "+ 5 % работам"),
    ("смета двенадцать", "смета 12"),
    ("смр одна целая четыре десятых", "смр 1.4"),
    ("мтр один целых двадцать пять сотых.", "мтр 1.25"),
    ("добавь двадцать пять процентов к материалам", "добавь 25 % к материалам"),
    ("ндс двадцать два", "ндс 22"),
    ("плюс сто двадцать процентов всему", "+ 120 % всему"),
    ("лимит восемь", "лимит 8"),
])
def test_normalize(said, expected):
    assert normalize(said) == expected
