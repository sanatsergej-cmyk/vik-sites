SPECIFIC = lambda x: f"[УТОЧНИТЬ: {x}]"  # noqa: E731


@dataclass
class Letter:
    subject: str
    body: str
    warnings: List[str] = field(default_factory=list)


def _val(value: Optional[str], label: str, warnings: List[str]) -> str:
    value = (value or "").strip()
    if value:
        return value
    warnings.append(label)
    return SPECIFIC(label)


def _money(x: float) -> str:
    return f"{x:,.0f}".replace(",", " ")


def build_letter(
    kind: str,
    service_id: str,
    *,
    contact_name: str = "",
    object_name: str = "",
    sender: str = "",
    company: str = "",
    phone: str = "",
    email: str = "",
    reason: str = "",
    total: Optional[float] = None,
    kp_date: str = "",
) -> Letter:
    if kind not in KINDS:
        raise ValueError("Неизвестный вид письма")
    if kind == "offer" and not reason.strip():
        raise ValueError("Для первичного предложения нужен конкретный повод (объект, закупка, событие)")
    svc = SERVICE_TEXT.get(service_id) or SERVICE_TEXT[""]
    w: List[str] = []
    name = _val(contact_name, "имя адресата", w)
    obj = _val(object_name, "объект", w)
    signer = _val(sender, "ваше имя", w)
    comp = (company or "").strip() or "ВиК"
    contacts = " · ".join(x for x in [phone.strip() or SPECIFIC("телефон"), email.strip()] if x)
    if not phone.strip():
        w.append("телефон")
    sign = f"С уважением,\n{signer}\n{comp}\n{contacts}"
    needs = "\n".join(f"— {n}" for n in svc["needs"])
    eta = "Первичную оценку по присланным материалам делаем в течение 2 часов — суток; если данных не хватает, укажем, каких именно."

    if kind == "reply_kp":
        total_line = f"Ориентировочная стоимость с НДС: {_money(total)} ₽ (состав — в коммерческом предложении).\n" if total else ""
        date_line = f" от {kp_date}" if kp_date else ""
        subject = f"Коммерческое предложение: {svc['topic']} — {obj}"
        body = (
            f"Здравствуйте, {name}!\n\n"
            f"Спасибо за обращение. По объекту «{obj}» направляем коммерческое предложение{date_line} — {svc['topic']}.\n\n"
            f"{svc['offer']}\n\n{total_line}"
            "Если по составу работ или срокам есть вопросы либо задача изменилась — напишите, уточним и пересчитаем.\n\n"
            f"Коммерческое предложение — во вложении.\n\n{sign}"
        )
    elif kind == "request_docs":
        subject = f"{svc['topic'].capitalize()}: что нужно для расчёта — {obj}"
        body = (
            f"Здравствуйте, {name}!\n\n"
            f"Спасибо за обращение по объекту «{obj}» ({svc['topic']}).\n\n{svc['offer']}\n\n"
            f"Чтобы подготовить расчёт, пришлите, пожалуйста:\n{needs}\n\n"
            f"Если каких-то документов пока нет — достаточно описания задачи. {eta}\n\n{sign}"
        )
    elif kind == "offer":
        subject = f"{svc['topic'].capitalize()}: {obj}"
        body = (
            f"Здравствуйте, {name}!\n\n"
            f"Пишу в связи с тем, что {reason.strip().rstrip('.')}.\n\n{svc['offer']}\n\n"
            f"Если задача актуальна, пришлите ТУ, проект или описание — оценим следующий шаг. {eta}\n\n"
            "Если вопрос вас не касается, просто ответьте «не актуально» — мы больше не будем писать.\n\n"
            f"{sign}"
        )
    else:
        date_line = f" от {kp_date}" if kp_date else ""
        subject = f"Re: Коммерческое предложение: {svc['topic']} — {obj}"
        body = (
            f"Здравствуйте, {name}!\n\n"
            f"Возвращаюсь к нашему коммерческому предложению{date_line} по объекту «{obj}». "
            "Подскажите, пожалуйста, получилось ли с ним ознакомиться и есть ли вопросы по составу работ или срокам.\n\n"
            "Если задача изменилась или нужны уточнения по документам — напишите, мы пересчитаем.\n\n"
            f"{sign}"
        )
    return Letter(subject=subject, body=body, warnings=sorted(set(w)))
